#!/usr/bin/env node
/**
 * Retrieval benchmark for the memory engine, run against the REAL store.
 *
 * Why this exists (the gap it closes): every tuning decision so far was argued
 * from probe sets of 6–10 queries that had themselves been used to design the
 * thing under test. The library's own rule — 【留出集】检索指标必须建在留出集上 —
 * says that is self-deception. This is a larger, separately authored set (65
 * queries over the whole live library) so a change can be called better or
 * worse on evidence.
 *
 * Metrics are the standard ones, deliberately not "is top-1 right":
 *   • recall@k  — did an answer appear in the first k at all
 *   • MRR       — how far down the first answer sat
 *   • nDCG@k    — graded position quality for multiple answers
 *   • precision@k on the JUNK set — the other half. A memory system that
 *     answers everything is worse than one that stays silent; kovey's whole
 *     budget design assumes relevance gating works.
 *
 * Relevance is declared by TEXT FRAGMENT, resolved against the live store at
 * run time. That is deliberate: cluster summaries are regenerated by
 * maintenance, so hard-coded ids rot. A fragment that matches nothing is a
 * benchmark bug and fails the run loudly rather than quietly scoring 0.
 *
 * Usage:
 *   node tools/benchmark/run.mjs                 # run, print, exit 0
 *   node tools/benchmark/run.mjs --save baseline # also write results JSON
 *   node tools/benchmark/run.mjs --compare a.json b.json
 *   DSS_DENSE=0  → force lexical-only (ablation)
 *   DSS_WORD_ROUTE=0 → word route off (matches the shipped default)
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import os from 'node:os'
import { MemoryEngine } from '../../lib/memory-engine.js'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(os.homedir(), '.dsh', 'storages', 'dsh-session-suite')
const CWD = 'D:\\AI sandbox\\dsh-sandbox\\DSH Optimize'
const QUERIES = path.join(HERE, 'queries.json')
const RESULTS = path.join(HERE, 'results')
const K = 5

const argv = process.argv.slice(2)
const flag = name => argv.includes(`--${name}`)
const opt = (name, fallback) => {
  const at = argv.indexOf(`--${name}`)
  return at >= 0 && argv[at + 1] ? argv[at + 1] : fallback
}

// --- compare mode -----------------------------------------------------------
if (flag('compare')) {
  const [a, b] = argv.filter(arg => !arg.startsWith('--'))
  if (!a || !b) {
    console.error('usage: node tools/benchmark/run.mjs --compare <a.json> <b.json>')
    process.exit(2)
  }
  const left = JSON.parse(fs.readFileSync(path.resolve(a), 'utf8'))
  const right = JSON.parse(fs.readFileSync(path.resolve(b), 'utf8'))
  const rows = ['top1', 'recallAt5', 'mrr', 'ndcgAt5', 'junkPrecisionAt5']
  console.log(`${left.label ?? a}  →  ${right.label ?? b}\n`)
  console.log('metric          before   after     delta')
  let worse = false
  for (const key of rows) {
    const from = left.summary[key] ?? 0
    const to = right.summary[key] ?? 0
    const delta = to - from
    if (delta < -0.0005) worse = true
    console.log(
      `${key.padEnd(14)} ${from.toFixed(4)}  ${to.toFixed(4)}  ${delta >= 0 ? '+' : ''}${delta.toFixed(4)}`,
    )
  }
  console.log('')
  console.log(worse ? '⚠ at least one metric regressed' : '✓ no metric regressed')
  process.exit(worse ? 1 : 0)
}

// --- run mode ---------------------------------------------------------------
const spec = JSON.parse(fs.readFileSync(QUERIES, 'utf8'))
const denseEnabled = process.env.DSS_DENSE !== '0'

const engine = new MemoryEngine({
  root: ROOT,
  log: () => {},
  config: {
    // Match the shipped profile defaults so the number means "what the user
    // actually gets", not a lab configuration.
    wordRoute: false,
    embedding: denseEnabled
      ? { enabled: true, provider: 'local', modelDir: 'D:\\AI agent cache\\dsh\\models\\bge-base-zh-v1.5' }
      : { enabled: false },
  },
})

// --- self-check: fragments must resolve, or the benchmark is lying ----------
const live = await engine.list({ cwd: CWD })
const normalise = value => String(value ?? '').replace(/\s+/g, ' ').trim()
const liveText = new Map(live.map(entry => [entry.id, normalise(entry.text)]))
if (live.length === 0) {
  console.error('FATAL: the live store read empty — is DSH_HOME correct?')
  process.exit(2)
}

const unresolved = []
const resolved = []
for (const testCase of [...spec.cases, ...(spec.junk ?? []), ...(spec.synonym ?? [])]) {
  const ids = []
  for (const fragment of testCase.want) {
    const needle = normalise(fragment)
    const hits = [...liveText].filter(([, text]) => text.includes(needle)).map(([id]) => id)
    if (hits.length === 0) unresolved.push(`${testCase.q} → 「${fragment}」`)
    ids.push(...hits)
  }
  resolved.push({ ...testCase, ids: [...new Set(ids)] })
}
if (unresolved.length > 0) {
  console.error(`FATAL: ${unresolved.length} relevance fragment(s) match no live entry:`)
  for (const line of unresolved) console.error(`  ${line}`)
  console.error('\nThe library changed under the benchmark. Re-author the set (or restore a store snapshot).')
  process.exit(2)
}

// --- measure ----------------------------------------------------------------
const ndcg = (ranks, relevantCount, k) => {
  let dcg = 0
  for (let position = 1; position <= k; position += 1) {
    if (ranks.includes(position)) dcg += 1 / Math.log2(position + 1)
  }
  let idcg = 0
  for (let position = 1; position <= Math.min(relevantCount, k); position += 1) {
    idcg += 1 / Math.log2(position + 1)
  }
  return idcg === 0 ? 0 : dcg / idcg
}

const measure = async queries => {
  const rows = []
  let top1 = 0
  let hit = 0
  let rr = 0
  let ndcgSum = 0
  for (const testCase of queries) {
    // touch:false — measuring must not rewrite access counts, or the run
    // changes the decay score of the library it is scoring.
    const ranked = (await engine.recall({ cwd: CWD, query: testCase.q, limit: 500, touch: false })).filter(
      entry => !entry.archived,
    )
    const wanted = new Set(testCase.ids)
    const ranks = ranked.map(entry => entry.id).filter(id => wanted.has(id)).map((_, index) => index + 1)
    const first = ranks.length > 0 ? Math.min(...ranks) : Infinity
    const topRanked = ranked.slice(0, K)
    rows.push({
      q: testCase.q,
      want: testCase.ids.length,
      rank: first === Infinity ? null : first,
      top5: topRanked.map(entry => `${normalise(entry.text).slice(0, 40)}`),
    })
    if (first === 1) top1 += 1
    if (first <= K) hit += 1
    rr += first === Infinity ? 0 : 1 / first
    ndcgSum += ndcg(ranks, testCase.ids.length, K)
  }
  const n = queries.length || 1
  return { rows, summary: { n, top1: top1 / n, recallAt5: hit / n, mrr: rr / n, ndcgAt5: ndcgSum / n } }
}

// Split the resolved cases into the three sets. The synonym cases are tagged
// in the spec and must be measured APART: they are the honest half, so folding
// their (lower) scores into the main summary would hide a regression in the set
// that guards behaviour — and vice versa.
const synonymSource = spec.synonym ?? []
const isSynonym = testCase => synonymSource.some(entry => entry.q === testCase.q)
const relevant = resolved.filter(testCase => testCase.want.length > 0 && !isSynonym(testCase))
const synonymQueries = resolved.filter(isSynonym)
const junk = resolved.filter(testCase => testCase.want.length === 0 && !isSynonym(testCase))

console.log(
  `store: ${live.length} live entries   queries: ${relevant.length} tuned + ${synonymQueries.length} synonym + ${junk.length} junk`,
)
console.log(`dense rerank: ${denseEnabled ? 'ON (profile default)' : 'OFF (DSS_DENSE=0)'}   wordRoute: OFF\n`)

const main = await measure(relevant)
const synonym = synonymQueries.length > 0 ? await measure(synonymQueries) : null

// Junk set: does the INJECTION path (select, with its relevance gate) stay
// silent on questions the library cannot answer? This is the precision half.
let junkInjected = 0
const junkRows = []
for (const testCase of junk) {
  const picked = await engine.select({ cwd: CWD, query: testCase.q, limit: 6, touch: false })
  if (picked.items.length > 0) junkInjected += 1
  junkRows.push({ q: testCase.q, injected: picked.items.length })
}

console.log('--- misses (rank > 5 or absent) ---')
const misses = main.rows.filter(row => row.rank === null || row.rank > K)
if (misses.length === 0) console.log('  (none)')
for (const row of misses) {
  console.log(`  ${row.rank === null ? 'MISS' : `rank ${row.rank}`}  ${row.q}`)
}
console.log('')
console.log('--- junk set (should inject nothing) ---')
for (const row of junkRows) {
  console.log(`  ${row.injected === 0 ? 'ok  ' : 'LEAK'}  injected ${row.injected}  ${row.q}`)
}
console.log('')

const summary = {
  ...main.summary,
  junkPrecisionAt5: junk.length > 0 ? (junk.length - junkInjected) / junk.length : 1,
  junkTotal: junk.length,
  junkLeaked: junkInjected,
}
console.log('--- summary (vocabulary-overlap set: regression protection, NOT generalisation) ---')
console.log(`top-1         ${summary.top1.toFixed(4)}  (${Math.round(summary.top1 * summary.n)}/${summary.n})`)
console.log(`recall@5      ${summary.recallAt5.toFixed(4)}  (${Math.round(summary.recallAt5 * summary.n)}/${summary.n})`)
console.log(`MRR           ${summary.mrr.toFixed(4)}`)
console.log(`nDCG@5        ${summary.ndcgAt5.toFixed(4)}`)
console.log(`junk silent   ${summary.junkPrecisionAt5.toFixed(4)}  (${junk.length - junkInjected}/${junk.length})`)
if (synonym) {
  console.log('--- synonym set (honest half: phrased WITHOUT the target vocabulary) ---')
  for (const row of synonym.rows) {
    console.log(`  ${row.rank === null ? 'MISS' : `rank ${row.rank}`}  ${row.q}`)
  }
  console.log(`top-1         ${synonym.summary.top1.toFixed(4)}  (${Math.round(synonym.summary.top1 * synonym.summary.n)}/${synonym.summary.n})`)
  console.log(`recall@5      ${synonym.summary.recallAt5.toFixed(4)}  (${Math.round(synonym.summary.recallAt5 * synonym.summary.n)}/${synonym.summary.n})`)
  console.log(`MRR           ${synonym.summary.mrr.toFixed(4)}`)
  console.log(`nDCG@5        ${synonym.summary.ndcgAt5.toFixed(4)}`)
}

const out = {
  label: `${denseEnabled ? 'dense' : 'lexical'} @ ${new Date().toISOString().slice(0, 19)}`,
  config: { dense: denseEnabled, wordRoute: false, store: ROOT, cwd: CWD, liveEntries: live.length },
  summary,
  rows: main.rows,
  junkRows,
}
const saveName = opt('save', '')
if (saveName) {
  fs.mkdirSync(RESULTS, { recursive: true })
  const file = path.join(RESULTS, `${saveName.replace(/[^\w.-]/g, '_')}.json`)
  fs.writeFileSync(file, JSON.stringify(out, null, 1), 'utf8')
  console.log(`\nsaved: ${file}`)
}
